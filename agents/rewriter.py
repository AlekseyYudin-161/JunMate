"""A5 Rewriter — формирует текст резюме в формате hh.ru."""

from core.llm import call_llm
from core.schemas import Profile, SkillMatch, ResumeOutput

PROMPT = """
Редактор резюме под hh.ru. Вход: Profile + Track + SkillMatch + история диалога.
GROUNDING: используй ТОЛЬКО факты из Profile и истории диалога. Запрещено выдумывать опыт/навыки/цифры/работодателей.
Можно: переформулировать, структурировать, акцентировать под роль, усиливать глаголами действия.
Если у проекта/опыта в Profile пустое или краткое описание, но в истории диалога пользователь приводил детали (что делал, задачи, результаты, метрики) — используй их для описания. СТРОГО в рамках GROUNDING: только то, что пользователь реально сказал в диалоге, ничего не добавляй от себя.
Измеримые результаты (метрики, проценты, числа: «30% быстрее», «покрытие 75%», «300→90 мс»), названные в Profile или диалоге, включай в буллеты опыта/проектов — они усиливают резюме.
Блоки hh.ru: «Желаемая должность», «О себе» (3-5 строк), «Ключевые навыки» (из have/partial; отдельным подблоком «Знание языков» из Profile.languages, если есть), «Опыт» (буллеты с глаголами), «Проекты», «Образование». Деловой тон, по-русски.
Если target_role пуст — используй вероятную роль из навыков/проектов или общую формулировку, не выдумывая.
В блок «Опыт» помещай ТОЛЬКО записи из Profile.experience (работа с работодателем: есть org/компания). Личные, учебные и pet-проекты (без работодателя) ВСЕГДА идут в блок «Проекты», даже если они масштабные и с метриками. Не переноси проекты в опыт.
Если блок пуст (нет опыта / нет проектов / нет образования / нет языков) — НЕ выводи его заголовок вообще. Пустые блоки не печатай.
Названия технологий, инструментов и языков — на английском (Python, Docker, SQL); общие слова — по-русски.
Пробелы (missing) НЕ вписывай в опыт — вынеси в warnings.
Верни ТОЛЬКО JSON ResumeOutput {fmt:"hh", content_markdown, warnings[]}.
"""

def rewrite_resume(
    profile: Profile, 
    track: str, 
    gap: SkillMatch, 
    history: list[dict]
) -> ResumeOutput:
    """Формирует итоговое резюме."""
    user_content = f"""
    Profile: {profile.model_dump_json()}
    Track: {track}
    SkillMatch: {gap.model_dump_json() if gap else 'None'}
    History: {history}
    """

    return call_llm(
        system=PROMPT,
        user=user_content,
        schema=ResumeOutput,
        tier="heavy",
        temperature=0.4,
        agent="rewriter"
    )
